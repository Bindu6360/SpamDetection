/**
 * Load and display statistics
 */
async function loadStatistics() {
    try {
        const response = await fetch(`${API_BASE_URL}/api/stats`);
        const data = await response.json();
        
        if (data.success) {
            displayStatistics(data);
        }
        
    } catch (error) {
        console.error('Error loading statistics:', error);
    }
}

/**
 * Display statistics on the page
 */
function displayStatistics(stats) {
    document.getElementById('totalPredictions').textContent = stats.total_predictions;
    document.getElementById('spamCount').textContent = stats.spam_count;
    document.getElementById('notSpamCount').textContent = stats.not_spam_count;
    document.getElementById('avgConfidence').textContent = `${stats.average_confidence}%`;
}

