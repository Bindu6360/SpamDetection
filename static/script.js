/**
 * Load and display prediction history
 */
async function loadHistory() {
    try {
        const response = await fetch(`${API_BASE_URL}/api/history?limit=10`);
        const data = await response.json();
        
        if (data.success && data.count > 0) {
            displayHistory(data.history);
        } else {
            displayEmptyHistory();
        }
        
    } catch (error) {
        console.error('Error loading history:', error);
        displayEmptyHistory();
    }
}

/**
 * Display history in the history list
 */
function displayHistory(history) {
    const historyList = document.getElementById('historyList');
    
    if (history.length === 0) {
        displayEmptyHistory();
        return;
    }
    
    historyList.innerHTML = history.map((item, index) => `
        <div class="history-item">
            <div class="history-item-header">
                <span class="history-item-badge ${item.prediction === 'Spam' ? 'spam' : 'safe'}">
                    ${item.prediction === 'Spam' ? '⚠️' : '✓'} ${item.prediction}
                </span>
                <span style="color: var(--text-muted); font-size: 0.9rem;">
                    ${new Date(item.created_at).toLocaleDateString()} ${new Date(item.created_at).toLocaleTimeString()}
                </span>
            </div>
            <div class="history-item-message">
                "${escapeHtml(item.message)}"
            </div>
            <div class="history-item-meta">
                <span>Confidence: ${item.confidence}%</span>
                <button onclick="copyHistoryItem('${escapeHtml(item.message)}')" style="background: none; border: none; color: var(--text-secondary); cursor: pointer; padding: 0;">
                    <i class="fas fa-copy"></i> Copy
                </button>
            </div>
        </div>
    `).join('');
}

/**
 * Display empty history message
 */
function displayEmptyHistory() {
    const historyList = document.getElementById('historyList');
    historyList.innerHTML = '<p class="empty-state">No predictions yet. Start detecting spam!</p>';
}

/**
 * Copy history item to clipboard
 */
function copyHistoryItem(message) {
    navigator.clipboard.writeText(message).then(() => {
        showToast('Message copied!', 'success');
    }).catch(() => {
        showToast('Failed to copy', 'error');
    });
}

/**
 * Clear all prediction history
 */
async function clearAllHistory() {
    if (!confirm('Are you sure you want to clear all prediction history? This action cannot be undone.')) {
        return;
    }
    
    try {
        const response = await fetch(`${API_BASE_URL}/api/clear-history`, {
            method: 'POST'
        });
        
        const data = await response.json();
        
        if (data.success) {
            displayEmptyHistory();
            loadStatistics(); // Refresh stats
            showToast('History cleared successfully', 'success');
        } else {
            showToast(data.error || 'Failed to clear history', 'error');
        }
        
    } catch (error) {
        console.error('Error clearing history:', error);
        showToast(`Error: ${error.message}`, 'error');
    }
}

