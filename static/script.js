/**
 * Send message to backend for spam detection
 */
async function detectSpam() {
    const messageInput = document.getElementById('messageInput');
    const message = messageInput.value.trim();
    const detectBtn = document.getElementById('detectBtn');
    
    // Validation
    if (!message) {
        showToast('Please enter a message', 'error');
        messageInput.focus();
        return;
    }
    
    if (message.length > 5000) {
        showToast('Message is too long (max 5000 characters)', 'error');
        return;
    }
    
    // Disable button and show loader
    detectBtn.disabled = true;
    detectBtn.querySelector('.btn-text').classList.add('hidden');
    detectBtn.querySelector('.btn-loader').classList.remove('hidden');
    
    try {
        // Make API call
        const response = await fetch(`${API_BASE_URL}/api/predict`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({ message: message })
        });
        
        const data = await response.json();
        
        if (data.success) {
            // Store result
            lastPredictionResult = data;
            
            // Display result
            displayResult(data);
            
            // Show success toast
            showToast(`✓ ${data.prediction}! Confidence: ${data.confidence}%`, 'success');
            
            // Refresh history and stats
            await loadHistory();
            await loadStatistics();
            
        } else {
            showToast(data.error || 'Prediction failed', 'error');
        }
        
    } catch (error) {
        console.error('Error:', error);
        showToast(`Error connecting to server: ${error.message}`, 'error');
    } finally {
        // Re-enable button and hide loader
        detectBtn.disabled = false;
        detectBtn.querySelector('.btn-text').classList.remove('hidden');
        detectBtn.querySelector('.btn-loader').classList.add('hidden');
    }
}

/**
 * Display prediction result in the result card
 */
function displayResult(result) {
    const resultCard = document.getElementById('resultCard');
    const resultContent = document.getElementById('resultContent');
    
    const isSpam = result.is_spam;
    const badge = isSpam ? 'spam' : 'safe';
    const badgeText = result.prediction;
    const icon = isSpam ? '⚠️' : '✓';
    const color = isSpam ? 'spam' : 'safe';
    
    resultContent.innerHTML = `
        <div class="result-badge ${badge}">
            ${icon} ${badgeText}
        </div>
        
        <div class="result-item">
            <div class="result-label">Message Preview</div>
            <div class="result-value">"${escapeHtml(result.message.substring(0, 100))}${result.message.length > 100 ? '...' : ''}"</div>
        </div>
        
        <div class="result-item">
            <div class="result-label">Confidence Score</div>
            <div class="result-value">${result.confidence}%</div>
            <div class="confidence-bar">
                <div class="confidence-fill" style="width: ${result.confidence}%"></div>
            </div>
        </div>
        
        <div class="result-item">
            <div class="result-label">Analysis</div>
            <div class="result-value">
                ${isSpam 
                    ? '🚫 This message appears to be spam. Be careful with clicking links or responding.' 
                    : '✓ This message appears to be legitimate.'}
            </div>
        </div>
    `;
    
    // Show result card with animation
    resultCard.classList.remove('hidden');
    resultCard.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

/**
 * Escape HTML special characters
 */
function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}

