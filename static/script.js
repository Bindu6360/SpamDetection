const API_BASE_URL = 'http://localhost:5000';
let lastPredictionResult = null;

// ============================================
// DOM MANIPULATION FUNCTIONS
// ============================================

/**
 * Display a toast notification message
 * @param {string} message - Message to display
 * @param {string} type - 'success', 'error', or 'info'
 * @param {number} duration - Duration in milliseconds
 */
function showToast(message, type = 'info', duration = 3000) {
    const toast = document.getElementById('toast');
    toast.textContent = message;
    toast.className = `toast show ${type}`;
    
    setTimeout(() => {
        toast.classList.remove('show');
    }, duration);
}

/**
 * Update character counter
 */
document.getElementById('messageInput').addEventListener('input', function() {
    document.getElementById('charCount').textContent = this.value.length;
});

/**
 * Scroll to detector section
 */
function scrollToDetector() {
    const detectorSection = document.getElementById('detector');
    detectorSection.scrollIntoView({ behavior: 'smooth' });
}

/**
 * Clear result card
 */
function clearResult() {
    const resultCard = document.getElementById('resultCard');
    resultCard.classList.add('hidden');
    lastPredictionResult = null;
}

/**
 * Copy message to clipboard
 */
function copyMessage() {
    if (!lastPredictionResult) {
        showToast('No message to copy', 'error');
        return;
    }
    
    const text = lastPredictionResult.message;
    navigator.clipboard.writeText(text).then(() => {
        showToast('Message copied to clipboard!', 'success');
    }).catch(() => {
        showToast('Failed to copy message', 'error');
    });
}

/**
 * Download result as text file
 */
function downloadResult() {
    if (!lastPredictionResult) {
        showToast('No result to download', 'error');
        return;
    }
    
    const result = lastPredictionResult;
    const text = `SPAM DETECTION RESULT
====================

Message:
${result.message}

Prediction: ${result.prediction}
Confidence: ${result.confidence}%

Timestamp: ${new Date().toLocaleString()}

Generated by SpamGuard - Spam Detection System
    `;
    
    // Create and download file
    const element = document.createElement('a');
    element.setAttribute('href', 'data:text/plain;charset=utf-8,' + encodeURIComponent(text));
    element.setAttribute('download', `spam_result_${Date.now()}.txt`);
    element.style.display = 'none';
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
    
    showToast('Result downloaded successfully!', 'success');
}

